// ─── tiny CSV reader (quoted fields with newlines) ─────────────────────────────
function readCsv(path: string): Record<string, string>[] {
  const text = readFileSync(path, 'utf8');
  const rows: string[][] = [];
  let row: string[] = [], field = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') q = false;
      else field += c;
    } else if (c === '"') q = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field.replace(/\r$/, '')); rows.push(row); row = []; field = ''; }
    else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const [head, ...body] = rows;
  return body.filter(r => r.length === head.length).map(r => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}

const stanzasOf = (poem: string) => poem.replace(/\r/g, '').trim().split(/\n\s*\n/)
  .map(s => s.split('\n').map(l => l.trim()).filter(Boolean)).filter(s => s.length);

function rng(seed: number) {
  return () => { seed = (seed * 1664525 + 1013904223) >>> 0; return seed / 2 ** 32; };
}

const pct = (x: number) => `${(100 * x).toFixed(1)}%`;
const out: string[] = [];
const say = (s = '') => { out.push(s); console.log(s); };

// ─── Spanish corpus ─────────────────────────────────────────────────────────────
const es = readCsv(join(HERE, 'data/raw/poems_es.csv')).filter(r => r.content && r.content.length > 40);
const r = rng(7);
const sample = es.map(p => ({ p, k: r() })).sort((a, b) => a.k - b.k).slice(0, 1000).map(x => x.p);

let old: ((t: string) => { allVerses: { field: string }[] }) | null = null;
const oldPath = join(HERE, 'data/work/old_poemParser.ts');
if (existsSync(oldPath)) old = (await import(oldPath)).parsePoem;

let verses = 0, neutralNew = 0, neutralOwn = 0, neutralOld = 0, tokens = 0, hitTokens = 0;
const topCounts = new Map<string, number>();
const oldCounts = new Map<string, number>();
const poemTop = new Map<string, number>();
const famShare = new Map<string, number>();
for (const { content } of sample) {
  const st = stanzasOf(content);
  const res = engine.scorePoem(st, 'es');
  poemTop.set(res.top, (poemTop.get(res.top) ?? 0) + 1);
  for (const [f, w] of Object.entries(res.families)) famShare.set(f, (famShare.get(f) ?? 0) + w / sample.length);
  st.flat().forEach((line, i) => {
    const v = res.verses[i];
    verses++;
    if (v.top === 'neutral') neutralNew++;
    if (!v.hits.length) neutralOwn++;
    topCounts.set(v.top, (topCounts.get(v.top) ?? 0) + 1);
    const toks = engine.tokenize(line).filter(t => t.length > 3);
    tokens += toks.length;
    hitTokens += v.hits.filter(h => h.token.length > 3).length;
  });
  if (old) for (const v of old(content).allVerses) {
    if (v.field === 'neutral') neutralOld++;
    oldCounts.set(v.field, (oldCounts.get(v.field) ?? 0) + 1);
  }
}

say('# Emotion engine — evaluation report');
say();
say(`Generated by \`emotion-lab/03_evaluate.ts\`. Lexicons: ${Object.keys(json('lib/emotions/lexicon.es.json').lemmas).length} Spanish lemmas, ${Object.keys(json('lib/emotions/lexicon.en.json').lemmas).length} English lemmas.`);
say();
say(`## Spanish corpus — 1,000 random poems, ${verses.toLocaleString('en')} verses`);
say();
say('| | previous lexicon | new: words of the verse only | new: with context (what the app shows) |');
say('|---|---|---|---|');
say(`| verses read as neutral | ${old ? pct(neutralOld / verses) : 'n/a'} | ${pct(neutralOwn / verses)} | ${pct(neutralNew / verses)} |`);
say(`| distinct emotions used | ${old ? [...oldCounts.keys()].filter(k => k !== 'neutral').length : 'n/a'} / 13 | | ${[...topCounts.keys()].filter(k => k !== 'neutral').length} / 40 |`);
say();
say(`Content words (4+ letters) carrying emotion: ${pct(hitTokens / tokens)}.`);
say();
const table = (m: Map<string, number>, total: number, n = 40) => {
  say('| emotion | share |'); say('|---|---|');
  [...m.entries()].sort((a, b) => b[1] - a[1]).slice(0, n).forEach(([k, c]) => say(`| ${k} | ${pct(c / total)} |`));
};
say('### Strongest emotion per verse (new)'); say(); table(topCounts, verses); say();
if (old) { say('### Strongest emotion per verse (previous)'); say(); table(oldCounts, verses, 14); say(); }
say('### Emotional mix by family (mean over poems)'); say();
table(famShare, 1); say();
say('### Dominant emotion per poem'); say(); table(poemTop, sample.length, 20); say();

// ─── English labeled corpus ─────────────────────────────────────────────────────
// The labels come from a 7-class emotion classifier (anger, disgust, fear, joy,
// neutral, sadness, surprise). Map our 40 emotions onto those 7.
const TO7: Record<string, string> = {
  alegría: 'joy', júbilo: 'joy', gozo: 'joy', serenidad: 'joy', gratitud: 'joy', amor: 'joy', deseo: 'joy',
  ternura: 'joy', devoción: 'joy', optimismo: 'joy', esperanza: 'joy', éxtasis: 'joy', honor: 'joy', orgullo: 'joy',
  asombro: 'surprise', misterio: 'surprise',
  tristeza: 'sadness', melancolía: 'sadness', soledad: 'sadness', nostalgia: 'sadness', duelo: 'sadness',
  desolación: 'sadness', resignación: 'sadness', anhelo: 'sadness', culpa: 'sadness', vergüenza: 'sadness',
  miedo: 'fear', angustia: 'fear', inseguridad: 'fear', desamparo: 'fear',
  furia: 'anger', frustración: 'anger', rencor: 'anger', indignación: 'anger', celos: 'anger',
  desprecio: 'disgust', asco: 'disgust', hastío: 'disgust', desengaño: 'disgust', deber: 'neutral',
};
const SEVEN = ['anger', 'disgust', 'fear', 'joy', 'neutral', 'sadness', 'surprise'];
const en = readCsv(join(HERE, 'data/raw/poems_en_emotions.csv'));
const prior: Record<string, number> = {};
for (const row of en) prior[row.label] = (prior[row.label] ?? 0) + 1;
const SIX = SEVEN.filter(k => k !== 'neutral');
const ours = en.map(row => {
  const res = engine.scorePoem(stanzasOf(row['poem content']), 'en');
  const seven: Record<string, number> = Object.fromEntries(SEVEN.map(k => [k, 0]));
  res.distribution.forEach((w, i) => { seven[TO7[IDS[i]]] += w; });
  return seven;
});
// Our 40 emotions fold unevenly onto 7 classes (14 of them land on "joy"), so
// also compare after standardising each class over the corpus: which class is
// unusually strong in this poem.
const stats = Object.fromEntries(SIX.map(k => {
  const xs = ours.map(o => o[k]);
  const m = xs.reduce((a, b) => a + b, 0) / xs.length;
  const sd = Math.sqrt(xs.reduce((a, b) => a + (b - m) ** 2, 0) / xs.length) || 1;
  return [k, { m, sd }];
}));
const scoreRaw = (o: Record<string, number>) => SIX.slice().sort((a, b) => o[b] - o[a]);
const scoreZ = (o: Record<string, number>) => SIX.slice().sort((a, b) => (o[b] - stats[b].m) / stats[b].sd - (o[a] - stats[a].m) / stats[a].sd);
const tally = (rank: (o: Record<string, number>) => string[]) => {
  let top1 = 0, top2 = 0;
  const conf: Record<string, Record<string, number>> = {};
  en.forEach((row, i) => {
    const r = rank(ours[i]);
    if (r[0] === row.label) top1++;
    if (r.slice(0, 2).includes(row.label)) top2++;
    conf[row.label] ??= {}; conf[row.label][r[0]] = (conf[row.label][r[0]] ?? 0) + 1;
  });
  return { top1, top2, conf };
};
const rawT = tally(scoreRaw), zT = tally(scoreZ);
const corr: Record<string, { x: number[]; y: number[] }> = Object.fromEntries(SEVEN.map(k => [k, { x: [], y: [] }]));
en.forEach((row, i) => { for (const k of SEVEN) { corr[k].x.push(ours[i][k]); corr[k].y.push(Number(row[k])); } });
const pearson = (x: number[], y: number[]) => {
  const mx = x.reduce((a, b) => a + b) / x.length, my = y.reduce((a, b) => a + b) / y.length;
  let n = 0, dx = 0, dy = 0;
  for (let i = 0; i < x.length; i++) { n += (x[i] - mx) * (y[i] - my); dx += (x[i] - mx) ** 2; dy += (y[i] - my) ** 2; }
  return dx && dy ? n / Math.sqrt(dx * dy) : 0;
};
const majority = Math.max(...Object.values(prior)) / en.length;
say(`## English corpus — ${en.length} poems with 7-class labels`);
say();
say('The labels come from an automatic classifier, not from human readers, so they are a reference point rather than ground truth. Our 40 emotions are folded onto its 7 classes for the comparison.');
say();
const emotional = en.filter(r => r.label !== 'neutral').length;
say(`Labels other than "neutral": ${emotional} poems (we never answer "neutral" on a whole poem, so the ${en.length - emotional} neutral ones always count as misses).`);
say();
say('| | top class = label | label in our top 2 |');
say('|---|---|---|');
say(`| always guess "${Object.entries(prior).sort((a, b) => b[1] - a[1])[0][0]}" (majority) | ${pct(majority)} | |`);
say(`| chance (6 classes) | ${pct(1 / 6)} | ${pct(2 / 6)} |`);
say(`| ours, raw shares | ${pct(rawT.top1 / en.length)} | ${pct(rawT.top2 / en.length)} |`);
say(`| ours, standardised per class | ${pct(zT.top1 / en.length)} | ${pct(zT.top2 / en.length)} |`);
say();
say('| class | correlation of our share with the label score |'); say('|---|---|');
for (const k of SIX) say(`| ${k} | ${pearson(corr[k].x, corr[k].y).toFixed(2)} |`);
say();
say('Confusion, standardised (rows: label, columns: our top class):'); say();
say(`| label \\ ours | ${SIX.join(' | ')} |`); say(`|---|${SIX.map(() => '---').join('|')}|`);
for (const g of SEVEN) if (zT.conf[g]) say(`| ${g} | ${SIX.map(c => zT.conf[g][c] ?? 0).join(' | ')} |`);
say();

